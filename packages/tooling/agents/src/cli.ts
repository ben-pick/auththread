import {
  existsSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../../..");
const skip = new Set([
  "node_modules",
  ".git",
  "dist",
  ".turbo",
  "coverage",
  ".wrangler",
  ".vitest-cache",
]);

const walk = (dir: string, out: string[] = []): string[] => {
  for (const entry of readdirSync(dir)) {
    if (skip.has(entry)) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path, out);
    else out.push(path);
  }
  return out;
};

const frontmatter = (text: string): Record<string, string | string[]> => {
  if (!text.startsWith("---\n")) return {};
  const end = text.indexOf("\n---", 4);
  if (end === -1) return {};
  const lines = text.slice(4, end).split("\n");
  const out: Record<string, string | string[]> = {};
  let key = "";
  for (const line of lines) {
    const match = /^([a-z-]+):\s*(.*)$/.exec(line);
    if (match) {
      key = match[1] ?? "";
      out[key] = (match[2] ?? "").replace(/^"(.*)"$/, "$1");
      continue;
    }
    const item = /^\s+-\s+"?(.*?)"?$/.exec(line);
    if (item && key !== "") {
      const current = out[key];
      out[key] = Array.isArray(current)
        ? [...current, item[1] ?? ""]
        : [item[1] ?? ""];
    }
  }
  return out;
};

const adrFiles = (): string[] =>
  readdirSync(join(root, "docs/decisions"))
    .filter((file) => file.endsWith(".md") && file !== "INDEX.md")
    .sort();

const readAdrs = () =>
  adrFiles().map((file) => {
    const text = readFileSync(join(root, "docs/decisions", file), "utf8");
    const meta = frontmatter(text);
    return {
      file,
      id: typeof meta.id === "string" ? meta.id : "",
      title: typeof meta.title === "string" ? meta.title : "",
      scope: Array.isArray(meta.scope) ? meta.scope : [],
    };
  });

const adrIndex = (): string => {
  const rows = readAdrs()
    .map(
      (adr) =>
        `| ${adr.id} | [${adr.title}](./${adr.file}) | ${adr.scope.join(", ")} |`,
    )
    .join("\n");
  return [
    "# Decisions",
    "",
    "Generated by `pnpm agents:index`. Do not edit by hand.",
    "",
    "| # | Decision | Scope |",
    "| --- | --- | --- |",
    rows,
    "",
  ].join("\n");
};

const rules = () =>
  readdirSync(join(root, ".agents/rules"))
    .filter((file) => file.endsWith(".md"))
    .sort()
    .map((file) => {
      const meta = frontmatter(
        readFileSync(join(root, ".agents/rules", file), "utf8"),
      );
      return {
        file,
        description:
          typeof meta.description === "string" ? meta.description : "",
        paths: Array.isArray(meta.paths) ? meta.paths : [],
      };
    });

const rulesIndex = (): string => {
  const rows = rules()
    .map(
      (rule) =>
        `| ${rule.paths.map((path) => `\`${path}\``).join(", ")} | [${rule.file}](.agents/rules/${rule.file}) |`,
    )
    .join("\n");
  return ["| Files | Rule |", "| --- | --- |", rows].join("\n");
};

const replaceBlock = (text: string, name: string, body: string): string => {
  const start = `<!-- ${name}:start -->`;
  const end = `<!-- ${name}:end -->`;
  const startAt = text.indexOf(start);
  const endAt = text.indexOf(end);
  if (startAt === -1 || endAt === -1)
    throw new Error(`missing ${name} markers`);
  return `${text.slice(0, startAt + start.length)}\n${body}\n${text.slice(endAt)}`;
};

const index = (): void => {
  writeFileSync(join(root, "docs/decisions/INDEX.md"), adrIndex());
  const agentsPath = join(root, "AGENTS.md");
  writeFileSync(
    agentsPath,
    replaceBlock(readFileSync(agentsPath, "utf8"), "rules-index", rulesIndex()),
  );
  console.log("wrote docs/decisions/INDEX.md and the rules index");
};

const links = (files: string[]): string[] => {
  const problems: string[] = [];
  for (const file of files.filter((path) => path.endsWith(".md"))) {
    const text = readFileSync(file, "utf8");
    for (const match of text.matchAll(/\]\(([^)\s]+)\)/g)) {
      const target = match[1] ?? "";
      if (/^(https?:|mailto:|#)/.test(target)) continue;
      const path = resolve(dirname(file), target.split("#")[0] ?? "");
      if (!existsSync(path))
        problems.push(`${relative(root, file)} links to missing ${target}`);
    }
  }
  return problems;
};

const secrets = (files: string[]): string[] => {
  const patterns = [
    /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
    /\bsk_live_[A-Za-z0-9]{16,}/,
    /\bAKIA[0-9A-Z]{16}\b/,
    /\bghp_[A-Za-z0-9]{20,}\b/,
    /\bxox[baprs]-[A-Za-z0-9-]{10,}\b/,
  ];
  const problems: string[] = [];
  for (const file of files) {
    if (file.endsWith("pnpm-lock.yaml")) continue;
    const text = readFileSync(file, "utf8");
    for (const pattern of patterns) {
      if (pattern.test(text))
        problems.push(
          `${relative(root, file)} looks like it contains a secret`,
        );
    }
  }
  return problems;
};

const check = (): void => {
  const problems: string[] = [];

  for (const adr of readAdrs()) {
    if (!/^\d{4}$/.test(adr.id))
      problems.push(`${adr.file} needs a four digit id`);
    if (!adr.file.startsWith(`${adr.id}-`))
      problems.push(`${adr.file} does not match its id ${adr.id}`);
    if (adr.title.length === 0) problems.push(`${adr.file} needs a title`);
  }

  for (const rule of rules()) {
    if (rule.description.length === 0)
      problems.push(`.agents/rules/${rule.file} needs a description`);
    if (rule.paths.length === 0)
      problems.push(`.agents/rules/${rule.file} needs at least one path`);
  }

  const files = walk(root).filter((file) => !file.includes("/.git/"));
  problems.push(...links(files), ...secrets(files));

  if (
    readFileSync(join(root, "docs/decisions/INDEX.md"), "utf8") !== adrIndex()
  ) {
    problems.push("docs/decisions/INDEX.md is stale, run pnpm agents:index");
  }

  const agents = readFileSync(join(root, "AGENTS.md"), "utf8");
  if (!agents.includes(rulesIndex()))
    problems.push("the AGENTS.md rules index is stale, run pnpm agents:index");

  if (problems.length > 0) {
    console.error(problems.map((problem) => `- ${problem}`).join("\n"));
    process.exit(1);
  }
  console.log("agent files are consistent");
};

const command = process.argv[2];
if (command === "index") index();
else if (command === "check") check();
else {
  console.error("usage: agents <check|index>");
  process.exit(1);
}
